def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest().upper()


def load_tsv(path: Path):
    symbols = []
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) < 2 or parts[1] == "MISSING":
            continue
        name = parts[0].strip()
        try:
            rva = int(parts[1], 16)
        except ValueError:
            continue
        if name:
            symbols.append((name, rva))
    # stable output, first occurrence wins
    dedup = {}
    for name, rva in symbols:
        dedup.setdefault(name, rva)
    return sorted(dedup.items(), key=lambda x: x[0].lower())


def main():
    lines = []
    lines.append("// Auto-generated by tools/gen_known_symbols.py. Do not edit.")
    lines.append("// Each block is keyed by the module SHA-256 and the exact file version.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("")
    lines.append("struct DS_KNOWN_SYMBOL")
    lines.append("{")
    lines.append("    const wchar_t* name;")
    lines.append("    DWORD rva;")
    lines.append("};")
    lines.append("")
    lines.append("struct DS_KNOWN_MODULE")
    lines.append("{")
    lines.append("    const wchar_t* name;")
    lines.append("    const wchar_t* sha256;")
    lines.append("    const wchar_t* version;")
    lines.append("    const DS_KNOWN_SYMBOL* symbols;")
    lines.append("    std::size_t count;")
    lines.append("};")
    lines.append("")

    module_arrays = []
    for mod in MODULES:
        digest = sha256(mod["path"])
        symbols = load_tsv(mod["tsv"])
        arr = mod["prefix"] + "Symbols"
        module_arrays.append((mod, digest, arr))
        lines.append("// " + mod["name"])
        lines.append("// Version: " + mod["version"])
        lines.append("// SHA256:  " + digest)
        lines.append(f"static const DS_KNOWN_SYMBOL {arr}[] = {{")
        for name, rva in symbols:
            escaped = name.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    {{ L"{escaped}", 0x{rva:X} }},')
        lines.append("};")
        lines.append("")

    lines.append("static const DS_KNOWN_MODULE kKnownModules[] = {")
    for mod, digest, arr in module_arrays:
        lines.append("    {")
        lines.append(f'        L"{mod["name"]}",')
        lines.append(f'        L"{digest}",')
        lines.append(f'        L"{mod["version"]}",')
        lines.append(f"        {arr},")
        lines.append(f"        _countof({arr})")
        lines.append("    },")
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
