#!/usr/bin/env python3
"""Generate the compiled-in SHA-256 -> RVA table from external JSON input.

The JSON file is intentionally NOT part of the repository. It lists every
module version whose addresses should be compiled into KnownSymbols.g.h.

Example (paths relative to the repository root):

{
  "modules": [
    {
      "name": "explorer.exe",
      "path": "_ref/explorer.exe",
      "tsv": "_analyze/symbols/explorer.tsv",
      "version": "6.3.9600.18231 (winblue_ltsb.160208-0600)",
      "prefix": "kExplorer18231"
    }
  ]
}

TSV rows are:
    normalized_name<TAB>0xRVA<TAB>size
Rows with MISSING are ignored.
"""

import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest().upper()


def resolve(path_text: str) -> Path:
    path = Path(path_text)
    return path if path.is_absolute() else ROOT / path


def load_tsv(path: Path):
    symbols = []
    for line in path.read_text(encoding="utf-8").splitlines():
        parts = line.split("\t")
        if len(parts) < 2 or parts[1] == "MISSING":
            continue
        name = parts[0].strip()
        try:
            rva = int(parts[1], 16)
        except ValueError:
            continue
        if name:
            symbols.append((name, rva))
    dedup = {}
    for name, rva in symbols:
        dedup.setdefault(name, rva)
    return sorted(dedup.items(), key=lambda item: item[0].lower())


def load_input(path: Path):
    data = json.loads(path.read_text(encoding="utf-8"))
    modules = data.get("modules")
    if not isinstance(modules, list) or not modules:
        raise SystemExit(f"{path}: 'modules' must be a non-empty list")
    return modules


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--input", required=True, type=Path,
                    help="external JSON module list (not committed)")
    ap.add_argument("--output", type=Path,
                    default=ROOT / "DirectStart.Hook" / "KnownSymbols.g.h")
    args = ap.parse_args(argv)

    input_path = args.input if args.input.is_absolute() else Path.cwd() / args.input
    if not input_path.is_file():
        raise SystemExit(f"input JSON not found: {input_path}")
    modules = load_input(input_path)

    lines = [
        "// Auto-generated by tools/gen_known_symbols.py. Do not edit.",
        "// Each block is keyed by the module SHA-256 and the exact file version.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "struct DS_KNOWN_SYMBOL",
        "{",
        "    const wchar_t* name;",
        "    DWORD rva;",
        "};",
        "",
        "struct DS_KNOWN_MODULE",
        "{",
        "    const wchar_t* name;",
        "    const wchar_t* sha256;",
        "    const wchar_t* version;",
        "    const DS_KNOWN_SYMBOL* symbols;",
        "    std::size_t count;",
        "};",
        "",
    ]

    module_arrays = []
    for mod in modules:
        name = mod.get("name")
        path_text = mod.get("path")
        tsv_text = mod.get("tsv")
        version = mod.get("version")
        prefix = mod.get("prefix")
        if not all(isinstance(x, str) and x for x in
                   (name, path_text, tsv_text, version, prefix)):
            raise SystemExit(f"invalid module entry: {mod!r}")

        module_path = resolve(path_text)
        tsv_path = resolve(tsv_text)
        if not module_path.is_file():
            raise SystemExit(f"module not found: {module_path}")
        if not tsv_path.is_file():
            raise SystemExit(f"TSV not found: {tsv_path}")

        digest = sha256(module_path)
        symbols = load_tsv(tsv_path)
        arr = f"{prefix}Symbols"
        module_arrays.append((name, digest, version, arr))
        lines.append("// " + name)
        lines.append("// Version: " + version)
        lines.append("// SHA256:  " + digest)
        lines.append(f"static const DS_KNOWN_SYMBOL {arr}[] = {{")
        for symbol, rva in symbols:
            escaped = symbol.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'    {{ L"{escaped}", 0x{rva:X} }},')
        lines.append("};")
        lines.append("")

    lines.append("static const DS_KNOWN_MODULE kKnownModules[] = {")
    for name, digest, version, arr in module_arrays:
        lines.append("    {")
        lines.append(f'        L"{name}",')
        lines.append(f'        L"{digest}",')
        lines.append(f'        L"{version}",')
        lines.append(f"        {arr},")
        lines.append(f"        _countof({arr})")
        lines.append("    },")
    lines.append("};")
    lines.append("")

    output = args.output if args.output.is_absolute() else ROOT / args.output
    output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {output} ({len(modules)} module versions)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
