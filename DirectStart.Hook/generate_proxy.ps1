param(
    [Parameter(Mandatory = $true)]
    [string]$Dumpbin,

    [Parameter(Mandatory = $true)]
    [string]$DllPath,

    [Parameter(Mandatory = $true)]
    [string]$DllName,

    [Parameter(Mandatory = $true)]
    [string]$Prefix,

    [string]$OutputDirectory = ""
)

$ErrorActionPreference = "Stop"

if (-not $OutputDirectory) {
    $OutputDirectory = Split-Path -Parent $MyInvocation.MyCommand.Path
}

if (-not (Test-Path -LiteralPath $Dumpbin)) {
    throw "dumpbin.exe was not found: $Dumpbin"
}
if (-not (Test-Path -LiteralPath $DllPath)) {
    throw "DLL was not found: $DllPath"
}

$dump = & $Dumpbin /nologo /exports $DllPath
if ($LASTEXITCODE -ne 0) {
    throw "dumpbin failed with exit code $LASTEXITCODE."
}

$exports = @()
foreach ($line in $dump) {
    if ($line -match '^\s*(\d+)\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(\S+)(?:\s+=\s+(\S+))?\s*$') {
        $name = [string]$Matches[2]
        if ($name -ne "[NONAME]") {
            $exports += [pscustomobject]@{
                Ordinal = [int]$Matches[1]
                Name = $name
            }
        }
    }
}

$exports = $exports |
    Sort-Object Ordinal |
    Group-Object Name |
    ForEach-Object { $_.Group[0] }

if ($exports.Count -lt 1) {
    throw "No named exports were parsed from $DllPath."
}

$defLines = @(
    "; AUTO-GENERATED by generate_proxy.ps1. Do not edit.",
    "LIBRARY $DllName",
    "",
    "EXPORTS"
)

$asmLines = @(
    "; AUTO-GENERATED by generate_proxy.ps1. Do not edit.",
    "OPTION CASEMAP:NONE",
    "",
    "EXTERN ${Prefix}Proxy_Dispatch:PROC",
    "",
    ".code"
)

$headerLines = @(
    "// AUTO-GENERATED by generate_proxy.ps1. Do not edit.",
    "#pragma once",
    "",
    "#include <cstddef>",
    "",
    "inline constexpr std::size_t k${Prefix}ExportCount = $($exports.Count);",
    "",
    "extern `"C`" void* g_${DllName}_procs[k${Prefix}ExportCount];",
    "",
    "inline constexpr const char* k${Prefix}ExportNames[] = {"
)

for ($index = 0; $index -lt $exports.Count; $index++) {
    $name = [string]$exports[$index].Name
    $safeName = $name -replace '[^A-Za-z0-9_]', '_'
    $stub = "${Prefix}Proxy_$safeName"

    $defLines += "    $name=$stub"
    $asmLines += ""
    $asmLines += "$stub PROC"
    $asmLines += "    mov r11d, $index"
    $asmLines += "    jmp ${Prefix}Proxy_Dispatch"
    $asmLines += "$stub ENDP"
    $headerLines += "    `"$name`","
}

$asmLines += ""
$asmLines += "END"
$headerLines += "};"

Set-Content -LiteralPath (Join-Path $OutputDirectory "$DllName.def") -Value $defLines -Encoding ascii
Set-Content -LiteralPath (Join-Path $OutputDirectory "${Prefix}Proxy.asm") -Value $asmLines -Encoding ascii
Set-Content -LiteralPath (Join-Path $OutputDirectory "${Prefix}Proxy.h") -Value $headerLines -Encoding ascii

Write-Host "Generated $($exports.Count) proxies for $DllName."
