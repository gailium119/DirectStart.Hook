param(
    [Parameter(Mandatory = $true)]
    [string]$Dumpbin,

    [string]$WinMMDll = "$env:WINDIR\System32\winmm.dll",
    [string]$OutputDirectory = $PSScriptRoot
)

$ErrorActionPreference = "Stop"

if (-not (Test-Path -LiteralPath $Dumpbin))
{
    throw "dumpbin.exe was not found: $Dumpbin"
}
if (-not (Test-Path -LiteralPath $WinMMDll))
{
    throw "winmm.dll was not found: $WinMMDll"
}

$dump = & $Dumpbin /nologo /exports $WinMMDll
if ($LASTEXITCODE -ne 0)
{
    throw "dumpbin failed with exit code $LASTEXITCODE."
}

$exports = @()
foreach ($line in $dump)
{
    if ($line -match '^\s*(\d+)\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(\S+)(?:\s+=\s+(\S+))?\s*$')
    {
        $name = [string]$Matches[2]
        if ($name -ne "[NONAME]")
        {
            $exports += [pscustomobject]@{
                Ordinal = [int]$Matches[1]
                Name = $name
            }
        }
    }
}

$exports = $exports |
    Sort-Object Ordinal |
    Group-Object Name |
    ForEach-Object { $_.Group[0] }

if ($exports.Count -lt 100)
{
    throw "Only $($exports.Count) named WINMM exports were parsed."
}

$defLines = @(
    "; AUTO-GENERATED by generate_winmm_proxy.ps1. Do not edit.",
    "LIBRARY winmm",
    "",
    "EXPORTS"
)

$asmLines = @(
    "; AUTO-GENERATED by generate_winmm_proxy.ps1. Do not edit.",
    "OPTION CASEMAP:NONE",
    "",
    "EXTERN g_winmm_procs:QWORD",
    "",
    ".code"
)

$headerLines = @(
    "// AUTO-GENERATED by generate_winmm_proxy.ps1. Do not edit.",
    "#pragma once",
    "",
    "#include <cstddef>",
    "",
    "inline constexpr std::size_t kWinMMExportCount = $($exports.Count);",
    "",
    "extern `"C`" void* g_winmm_procs[kWinMMExportCount];",
    "",
    "inline constexpr const char* kWinMMExportNames[] = {"
)

for ($index = 0; $index -lt $exports.Count; $index++)
{
    $name = [string]$exports[$index].Name
    $safeName = $name -replace '[^A-Za-z0-9_]', '_'
    $stub = "WinMMProxy_$safeName"
    $offset = $index * 8

    $defLines += "    $name=$stub"
    $asmLines += ""
    $asmLines += "$stub PROC"
    $asmLines += "    jmp qword ptr [g_winmm_procs + $offset]"
    $asmLines += "$stub ENDP"
    $headerLines += "    `"$name`","
}

$asmLines += ""
$asmLines += "END"
$headerLines += "};"

Set-Content -LiteralPath (Join-Path $OutputDirectory "winmm.def") -Value $defLines -Encoding ascii
Set-Content -LiteralPath (Join-Path $OutputDirectory "WinMMProxy.asm") -Value $asmLines -Encoding ascii
Set-Content -LiteralPath (Join-Path $OutputDirectory "WinMMProxy.h") -Value $headerLines -Encoding ascii

Write-Host "Generated $($exports.Count) name-based WINMM proxies."
